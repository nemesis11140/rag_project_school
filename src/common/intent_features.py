def extract_features(text: str) -> List[float]:
    """4 维人工特征，与 TF-IDF 特征拼接后送入分类器。"""
    if not text:
        text = ""

    professional_count = sum(1 for kw in PROFESSIONAL_KEYWORDS if kw in text)
    general_count = sum(1 for kw in GENERAL_KEYWORDS if kw in text)

    return [
        float(professional_count),
        float(general_count),
        float(1 if professional_count > general_count else 0),
        float(len(text)),
    ]
